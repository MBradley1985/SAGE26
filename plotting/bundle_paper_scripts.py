#!/usr/bin/env python
"""
bundle_paper_scripts.py -- make paper1_plots.py and paper2_plots.py self-contained.

Each paper script uses functions from paper_plots.py (and paper1_plots.py also from
random_plotting_scripts/paper1_referee.py, which is not in git).  This tool copies
exactly the top-level code those functions need -- found by following names from
the script's `pp.X` / `ref.X` uses through every definition they depend on -- into
the script between the BUNDLE markers, verbatim and in source order.  The scripts
then run with nothing but the SAGE26 data/ directory beside them.

Run it again after changing paper_plots.py or paper1_referee.py:
    python plotting/bundle_paper_scripts.py
"""

import ast
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER_PLOTS = os.path.join(HERE, 'paper_plots.py')
REFEREE = os.path.join(HERE, 'random_plotting_scripts', 'paper1_referee.py')
STYLE = os.path.join(HERE, 'kieren_cohare_palatino_sty.mplstyle')
BEGIN = '# ==================== BEGIN BUNDLE (generated by bundle_paper_scripts.py; do not edit) ===================='
END = '# ==================== END BUNDLE ===================='


def _defs(st):
    """Top-level names a statement binds."""
    if isinstance(st, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        return {st.name}
    if isinstance(st, (ast.Import, ast.ImportFrom)):
        return {(a.asname or a.name).split('.')[0] for a in st.names}
    out = set()
    for n in ast.walk(st):
        if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Store):
            out.add(n.id)
        elif isinstance(n, (ast.FunctionDef, ast.ClassDef)) and isinstance(st, (ast.If, ast.Try, ast.With)):
            out.add(n.name)
    return out


def _uses(st, prefixes):
    out = set()
    for n in ast.walk(st):
        if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load):
            out.add(n.id)
        elif isinstance(n, ast.Attribute) and isinstance(n.value, ast.Name) and n.value.id in prefixes:
            out.add(n.attr)
    return out


def _is_main_guard(st):
    return (isinstance(st, ast.If) and isinstance(st.test, ast.Compare)
            and isinstance(st.test.left, ast.Name) and st.test.left.id == '__name__')


def _statements(path, skip):
    src = open(path).read()
    tree = ast.parse(src)
    lines = src.splitlines(keepends=True)
    out = []
    body = tree.body
    for i, st in enumerate(body):
        if i == 0 and isinstance(st, ast.Expr) and isinstance(st.value, ast.Constant):
            continue                                   # module docstring
        if _is_main_guard(st) or skip(st, lines):
            continue
        # keep the comments directly above the statement
        start = st.lineno - 1
        while start > 0 and lines[start - 1].lstrip().startswith('#'):
            start -= 1
        if hasattr(st, 'decorator_list') and st.decorator_list:
            start = min(start, st.decorator_list[0].lineno - 1)
        text = ''.join(lines[start:st.end_lineno])
        out.append(dict(st=st, text=text, defs=_defs(st), uses=_uses(st, {'pp'}),
                        always=isinstance(st, (ast.Import, ast.ImportFrom))
                        or (isinstance(st, ast.Expr) and isinstance(st.value, ast.Call))))
    return out


def _closure(stmts, roots):
    need, keep = set(roots), set()
    changed = True
    while changed:
        changed = False
        for i, s in enumerate(stmts):
            if i in keep:
                continue
            if s['always'] or (s['defs'] & need):
                keep.add(i)
                new = s['uses'] - need
                if new:
                    need |= new
                changed = True
    return [stmts[i] for i in sorted(keep)]


def _roots(script_src, prefix):
    tree = ast.parse(script_src)
    return {n.attr for n in ast.walk(tree)
            if isinstance(n, ast.Attribute) and isinstance(n.value, ast.Name) and n.value.id == prefix}


def _skip_referee(st, lines):
    text = ''.join(lines[st.lineno - 1:st.end_lineno])
    return ('paper_plots' in text and isinstance(st, (ast.Import, ast.ImportFrom))) or 'sys.path.insert' in text


def bundle(script, with_referee):
    src = open(script).read()
    head, _, rest = src.partition(BEGIN + '\n')
    _, _, tail = rest.partition(END + '\n')
    if not tail:
        sys.exit(f'{script}: BUNDLE markers not found')
    own = head + tail

    pp_stmts = _statements(PAPER_PLOTS, lambda st, lines: False)
    roots = _roots(own, 'pp') | {'setup_style'}
    parts = []
    ref_kept = []
    if with_referee:
        ref_stmts = _statements(REFEREE, _skip_referee)
        ref_kept = _closure(ref_stmts, _roots(own, 'ref'))
        for s in ref_kept:              # the referee code reaches paper_plots through pp.X
            roots |= {n.attr for n in ast.walk(s['st']) if isinstance(n, ast.Attribute)
                      and isinstance(n.value, ast.Name) and n.value.id == 'pp'}
    pp_kept = _closure(pp_stmts, roots)

    # names the script defines itself must not shadow bundled ones
    own_defs = set()
    for st in ast.parse(own).body:
        own_defs |= _defs(st)
    bundled = set().union(*(s['defs'] for s in pp_kept + ref_kept))
    clash = (own_defs & bundled) - {'os', 'sys', 'np', 'h5', 'time', 'argparse', 'glob', 'pickle',
                                    'subprocess', 'importlib', 'Mapping', 'warnings'}
    clash -= {'matplotlib'}
    ref_renames = {}
    if with_referee:     # the referee module's own versions of paper_plots names get a ref_ prefix
        pp_defs = set().union(*(s['defs'] for s in pp_kept))
        rdefs = set().union(*(s['defs'] for s in ref_kept))
        imports = set().union(*(s['defs'] for s in pp_kept + ref_kept
                                if isinstance(s['st'], (ast.Import, ast.ImportFrom))))
        ref_renames = {n: 'ref_' + n for n in (pp_defs & rdefs) - imports}
    if clash:
        sys.exit(f'{script}: name clash between the script and the bundled code: {sorted(clash)}')

    style = open(STYLE).read()
    parts.append('# ---- matplotlib style (plotting/kieren_cohare_palatino_sty.mplstyle) ----\n'
                 f'_BUNDLED_STYLE = {style!r}\n\n')
    parts.append('# ---- from plotting/paper_plots.py ----\n')
    for s in pp_kept:
        t = s['text']
        if isinstance(s['st'], ast.FunctionDef) and s['st'].name == 'setup_style':
            t = t.replace('plt.style.use("./plotting/kieren_cohare_palatino_sty.mplstyle")',
                          '_use_bundled_style()')
        parts.append(t.rstrip('\n') + '\n\n')
    parts.append('''
def _use_bundled_style():
    import tempfile
    with tempfile.NamedTemporaryFile('w', suffix='.mplstyle', delete=False) as f:
        f.write(_BUNDLED_STYLE)
    plt.style.use(f.name)
    os.remove(f.name)


pp = sys.modules[__name__]       # the bundled paper_plots code, reached as pp.X
''')
    if with_referee:
        parts.append('\n# ---- from plotting/random_plotting_scripts/paper1_referee.py ----\n')
        for s in ref_kept:
            t = s['text']
            for old, new in ref_renames.items():
                t = re.sub(rf'(?<![.\w]){old}\b', new, t)
            parts.append(t.rstrip('\n') + '\n\n')
        parts.append('ref = pp                         # the bundled paper1_referee code, reached as ref.X\n')
    out = head + BEGIN + '\n' + ''.join(parts) + END + '\n' + tail
    open(script, 'w').write(out)
    n = sum(s['text'].count('\n') for s in pp_kept + ref_kept)
    print(f'{os.path.basename(script)}: bundled {len(pp_kept)} paper_plots statements'
          + (f' and {len(ref_kept)} referee statements' if with_referee else '') + f' ({n} lines)')


if __name__ == '__main__':
    bundle(os.path.join(HERE, 'paper2_plots.py'), with_referee=False)
    bundle(os.path.join(HERE, 'paper1_plots.py'), with_referee=True)
